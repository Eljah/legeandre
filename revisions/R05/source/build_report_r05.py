def txt(s,x,y,w,style='body',maxh=None):
 p=Paragraph(s,styles[style]);_,hh=p.wrap(w,2000)
 if maxh is not None and hh>maxh+0.1:raise ValueError(f'Overflow {PAG}: {hh}>{maxh}: {s[:70]}')
