def block(s,x,y,w,bg=PALE,style='body',pad=14,maxh=None):
 p=Paragraph(s,styles[style]);_,hh=p.wrap(w-2*pad,2000)
 if maxh is not None and hh+2*pad>maxh:raise ValueError(f'Block overflow p{PAG}')
 c.setFillColor(bg);c.roundRect(x,H-y-hh-2*pad,w,hh+2*pad,7,stroke=0,fill=1);p.drawOn(c,x+pad,H-y-pad-hh);return hh+2*pad

